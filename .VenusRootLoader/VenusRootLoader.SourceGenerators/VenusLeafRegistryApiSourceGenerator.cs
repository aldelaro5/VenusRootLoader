    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddEmbeddedAttributeDefinition();
            ctx.AddSource(
                $"{ExposeFromVenusAttribute}.g.cs",
                SourceText.From(AttributeSourceCode, Encoding.UTF8));
        });

        IncrementalValuesProvider<LeafTypeInfo> providerExposeRegisterLeafType = context
            .SyntaxProvider
            .ForAttributeWithMetadataName(
                $"{Namespace}.{ExposeFromVenusAttribute}",
                DummyPredicate,
                TransformLeafType);

        IncrementalValuesProvider<LeafCreateTypeInfo> providerExposeCreateLeafType = context
            .SyntaxProvider
            .ForAttributeWithMetadataName(
                $"{Namespace}.{ExposeCreateFromVenusAttribute}",
                DummyPredicate,
                TransformLeafCreateType);

        IncrementalValueProvider<ImmutableArray<LeafInitializationMethodInfo>> providerLeafInitializationMethod =
            context
                .SyntaxProvider
                .ForAttributeWithMetadataName(
                    $"{Namespace}.{LeafInitializeFromNewAttribute}",
                    DummyPredicate,
                    TransformLeafInitializationMethod)
                .Collect();

        IncrementalValueProvider<ImmutableArray<VenusLeafApiInfo>> finalRegisterProvider =
            providerExposeRegisterLeafType.Combine(providerLeafInitializationMethod)
                .Select((x, _) => new VenusLeafApiInfo
                {
                    LeafTypeInfo = x.Left,
                    LeafInitializationMethodInfo = x.Right.SingleOrDefault(y => y.LeafTypeName == x.Left.LeafTypeName)
                })
                .Collect();

        IncrementalValueProvider<ImmutableArray<VenusCreateLeafApiInfo>> finalCreateProvider =
            providerExposeCreateLeafType.Combine(providerLeafInitializationMethod)
                .Select((x, _) => new VenusCreateLeafApiInfo
                {
                    LeafCreateTypeInfo = x.Left,
                    LeafInitializationMethodInfo = x.Right.SingleOrDefault(y => y.LeafTypeName == x.Left.LeafTypeName)
                })
                .Collect();

        IncrementalValueProvider<ImmutableArray<LeafInitializationMethodInfo>> providerMapEntityInitialization = context
            .SyntaxProvider
            .ForAttributeWithMetadataName(
                $"{Namespace}.{MapEntityInitializeFromNewAttributeName}",
                DummyPredicate,
                TransformLeafInitializationMethod)
            .Collect();

        context.RegisterSourceOutput(finalRegisterProvider, GenerateCode);
        context.RegisterSourceOutput(finalCreateProvider, GenerateCreateCode);
        context.RegisterSourceOutput(providerMapEntityInitialization, GenerateCodeMapEntityRegistration);
    }

    private static bool DummyPredicate(SyntaxNode syntaxNode, CancellationToken cancellationToken) => true;

    private static LeafTypeInfo TransformLeafType(
        GeneratorAttributeSyntaxContext syntaxContext,
        CancellationToken cancellationToken)
    {
        INamedTypeSymbol leafTypeSymbol =
            (INamedTypeSymbol)syntaxContext.SemanticModel.GetDeclaredSymbol(
                syntaxContext.TargetNode,
                cancellationToken)!;

        INamedTypeSymbol? orderAfterTypeSymbol = null;
        INamedTypeSymbol? leakKeyTypeSymbol = null;
        TypedConstant orderAfterArgument = syntaxContext.Attributes.Single().ConstructorArguments[0];
        TypedConstant leafKeyTypeArguments = syntaxContext.Attributes.Single().ConstructorArguments[1];
        TypedConstant withRegisterMethodArgument = syntaxContext.Attributes.Single().ConstructorArguments[2];
        if (!orderAfterArgument.IsNull)
            orderAfterTypeSymbol = (INamedTypeSymbol)orderAfterArgument.Value!;
        if (!leafKeyTypeArguments.IsNull)
            leakKeyTypeSymbol = (INamedTypeSymbol)leafKeyTypeArguments.Value!;

        return new()
        {
            LeafTypeName = leafTypeSymbol.Name,
            LeafTypeDisplayString = leafTypeSymbol.ToDisplayString(),
            OrderAfterTypeName = orderAfterTypeSymbol?.ToDisplayString(),
            LeafKeyTypeName = leakKeyTypeSymbol?.ToDisplayString(),
            WithRegisterMethod = (bool)withRegisterMethodArgument.Value!
        };
    }

    private static LeafCreateTypeInfo TransformLeafCreateType(
        GeneratorAttributeSyntaxContext syntaxContext,
        CancellationToken cancellationToken)
    {
        INamedTypeSymbol leafTypeSymbol =
            (INamedTypeSymbol)syntaxContext.SemanticModel.GetDeclaredSymbol(
                syntaxContext.TargetNode,
                cancellationToken)!;

        return new()
        {
            LeafTypeName = leafTypeSymbol.Name,
            LeafTypeDisplayString = leafTypeSymbol.ToDisplayString()
        };
    }

    private static LeafInitializationMethodInfo TransformLeafInitializationMethod(
        GeneratorAttributeSyntaxContext syntaxContext,
        CancellationToken cancellationToken)
    {
        IMethodSymbol initializeMethodSymbol =
            (IMethodSymbol)syntaxContext.SemanticModel.GetDeclaredSymbol(
                syntaxContext.TargetNode,
                cancellationToken)!;
        ImmutableArray<TypedConstant> constructorArguments = syntaxContext.Attributes.Single().ConstructorArguments;
        TypedConstant? firstParameterIsKeyArgument = constructorArguments.Length > 0 ? constructorArguments[0] : null;

        return new()
        {
            LeafTypeName = initializeMethodSymbol.ContainingType.Name,
            LeafTypeDisplayString = initializeMethodSymbol.ContainingType.ToDisplayString(),
            MethodName = initializeMethodSymbol.Name,
            MethodParameters = BuildMethodSignatureParameters(
                initializeMethodSymbol,
                (bool?)firstParameterIsKeyArgument?.Value ?? false),
            CallingParameters = BuildMethodCallingParameters(
                initializeMethodSymbol,
                (bool?)firstParameterIsKeyArgument?.Value ?? false)
        };
    }

    private static string BuildMethodSignatureParameters(IMethodSymbol registerMethodSymbol, bool firstParameterIsKey)
    {
        IEnumerable<string> parameters = registerMethodSymbol.Parameters
            .Select(p => p.ToDisplayString());
        if (firstParameterIsKey)
            parameters = parameters.Skip(1);
        return string.Join(MethodParameterSeparator, parameters);
    }

    private static string BuildMethodCallingParameters(IMethodSymbol symbolMethod, bool firstParameterIsKey)
    {
        IEnumerable<string> parameters = symbolMethod.Parameters.Select(p => p.Name);
        if (firstParameterIsKey)
            parameters = parameters.Skip(1);
        return string.Join(", ", parameters);
    }

    private static void GenerateCode(SourceProductionContext context, ImmutableArray<VenusLeafApiInfo> leafTypeInfos)
    {
        foreach (VenusLeafApiInfo info in leafTypeInfos)
        {
            string venusSourceCode = VenusSourceCodeTemplate.Replace(
                "{{methods}}",
                BuildVenusRegistryApiMethodsSourceCode(info));
            context.AddSource(
                $"Venus{info.LeafTypeInfo.LeafTypeName}.g.cs",
                SourceText.From(venusSourceCode, Encoding.UTF8));
        }
    }

    private static void GenerateCreateCode(
        SourceProductionContext context,
        ImmutableArray<VenusCreateLeafApiInfo> leafTypeInfos)
    {
        foreach (VenusCreateLeafApiInfo info in leafTypeInfos)
        {
            string venusSourceCode = VenusSourceCodeTemplate.Replace(
                "{{methods}}",
                BuildVenusCreateApiMethodsSourceCode(info));
            context.AddSource(
                $"Venus{info.LeafCreateTypeInfo.LeafTypeName}.g.cs",
                SourceText.From(venusSourceCode, Encoding.UTF8));
        }
    }

    private static string BuildVenusRegistryApiMethodsSourceCode(VenusLeafApiInfo venusLeafApiInfo)
    {
        string template = venusLeafApiInfo switch
        {
            { LeafTypeInfo.WithRegisterMethod: false } => VenusLeafGetMethodsTemplate,
            { LeafTypeInfo.OrderAfterTypeName: not null, LeafInitializationMethodInfo: null } =>
                VenusLeafRegistryApiWithOrderingWithoutInitializeTemplate,
            { LeafTypeInfo.OrderAfterTypeName: not null, LeafInitializationMethodInfo: not null } =>
                VenusLeafRegistryApiWithOrderingWithInitializeTemplate,
            { LeafTypeInfo.LeafKeyTypeName: not null, LeafInitializationMethodInfo: not null } =>
                VenusLeafRegistryApiWithInitializationUsingBranchTemplate,
            _ => venusLeafApiInfo.LeafInitializationMethodInfo is null
                ? VenusLeafRegistryApiWithoutInitializeTemplate
                : VenusLeafRegistryApiWithInitializationTemplate
        };

        StringBuilder sb = new(template);
        sb.Replace("{{orderAfterTypeName}}", venusLeafApiInfo.LeafTypeInfo.OrderAfterTypeName ?? "");
        sb.Replace("{{leafKeyTypeName}}", venusLeafApiInfo.LeafTypeInfo.LeafKeyTypeName ?? "");

        FillCommonInfo(
            sb,
            venusLeafApiInfo.LeafTypeInfo.LeafTypeName,
            venusLeafApiInfo.LeafTypeInfo.LeafTypeDisplayString,
            venusLeafApiInfo.LeafInitializationMethodInfo);

        return sb.ToString();
    }

    private static string BuildVenusCreateApiMethodsSourceCode(VenusCreateLeafApiInfo venusCreateLeafApiInfo)
    {
        string template = venusCreateLeafApiInfo.LeafInitializationMethodInfo is null
            ? VenusLeafWithoutInitializeCreateMethodTemplate
            : VenusLeafWithInitializeCreateMethodTemplate;

        StringBuilder sb = new(template);

        FillCommonInfo(
            sb,
            venusCreateLeafApiInfo.LeafCreateTypeInfo.LeafTypeName,
            venusCreateLeafApiInfo.LeafCreateTypeInfo.LeafTypeDisplayString,
            venusCreateLeafApiInfo.LeafInitializationMethodInfo);

        return sb.ToString();
    }

    private static void GenerateCodeMapEntityRegistration(
        SourceProductionContext context,
        ImmutableArray<LeafInitializationMethodInfo> mapEntityInitializationInfos)
    {
        string venusSourceCode = VenusSourceCodeTemplate.Replace(
            "{{methods}}",
            string.Join("\n\n", mapEntityInitializationInfos.Select(BuildVenusMapEntityRegisterMethodSourceCode)));

        context.AddSource("VenusMapEntityRegistration.g.cs", SourceText.From(venusSourceCode, Encoding.UTF8));
    }

    private static string BuildVenusMapEntityRegisterMethodSourceCode(
        LeafInitializationMethodInfo venusMapEntityRegisterMethodInfo)
    {
        StringBuilder sb = new(MapEntityRegisterMethodTemplate);

        FillCommonInfo(
            sb,
            venusMapEntityRegisterMethodInfo.LeafTypeName,
            venusMapEntityRegisterMethodInfo.LeafTypeDisplayString,
            venusMapEntityRegisterMethodInfo);

        return sb.ToString();
    }

    private static void FillCommonInfo(
        StringBuilder sb,
        string leafTypeName,
        string leafTypeDisplayString,
        LeafInitializationMethodInfo? venusMapEntityRegisterMethodInfo)
    {
        string typeNameWithoutLeafSuffix = leafTypeName[..^4];
        sb.Replace("{{leafTypeName}}", leafTypeDisplayString);
        sb.Replace("{{leafTypeNameWithoutLeafSuffix}}", typeNameWithoutLeafSuffix);
        sb.Replace("{{leafTypeNamePluralizedWithoutLeafSuffix}}", typeNameWithoutLeafSuffix.Pluralize());
        sb.Replace("{{initializeMethodParameters}}", venusMapEntityRegisterMethodInfo?.MethodParameters ?? "");
        sb.Replace("{{initializeMethodName}}", venusMapEntityRegisterMethodInfo?.MethodName ?? "");
        sb.Replace("{{initializeMethodCallingParameters}}", venusMapEntityRegisterMethodInfo?.CallingParameters ?? "");
    }
